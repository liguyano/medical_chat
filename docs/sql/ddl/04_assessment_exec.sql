    operator_id                    BIGINT       NOT NULL DEFAULT 0,
    creator                        VARCHAR(64)  NOT NULL DEFAULT '',
    updator                        VARCHAR(64)  NOT NULL DEFAULT '',
    create_time                    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time                    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted                        SMALLINT     NOT NULL DEFAULT 0
);
COMMENT ON TABLE  assessment_action_record IS 'Braden/跌倒护理措施逐条记录；AI 建议先标记 pending，护士确认后生效';
COMMENT ON COLUMN assessment_action_record.action_source IS 'rule_recommended / ai_suggested / nurse_selected';
COMMENT ON COLUMN assessment_action_record.action_status IS 'pending / selected / notified / executed / cancelled';
CREATE INDEX ix_action_record_instance ON assessment_action_record (assessment_instance_id);

