-- ----------------------------
-- 10. assessment_review  护士评估复核
-- ----------------------------
CREATE TABLE assessment_review (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_no              VARCHAR(64)  NOT NULL,
    assessment_instance_id BIGINT       NOT NULL,
    ai_submission_id       BIGINT       NOT NULL DEFAULT 0,
    nurse_submission_id    BIGINT       NOT NULL DEFAULT 0,
    final_submission_id    BIGINT       NOT NULL DEFAULT 0,
    reviewer_id            BIGINT       NOT NULL,
    review_status          VARCHAR(32)  NOT NULL DEFAULT 'pending',
    supplementary_inquiry  TEXT         NOT NULL DEFAULT '',
    correction_reason      VARCHAR(1000) NOT NULL DEFAULT '',
    reviewed_at            TIMESTAMP(3),
    creator                VARCHAR(64)  NOT NULL DEFAULT '',
    updator                VARCHAR(64)  NOT NULL DEFAULT '',
    create_time            TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time            TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted                SMALLINT     NOT NULL DEFAULT 0
);
COMMENT ON TABLE  assessment_review IS '护士复核记录；只保存复核关系和说明，具体答案仍在 assessment_answer';
COMMENT ON COLUMN assessment_review.review_status IS 'pending / reviewed / returned';
CREATE UNIQUE INDEX ux_review_no       ON assessment_review (review_no)              WHERE deleted = 0;
CREATE        INDEX ix_review_instance ON assessment_review (assessment_instance_id);

-- ----------------------------
-- 11. assessment_comparison  评估人机对比主表
-- ----------------------------
CREATE TABLE assessment_comparison (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_instance_id BIGINT          NOT NULL,
    ai_submission_id       BIGINT          NOT NULL,
    nurse_submission_id    BIGINT          NOT NULL,
    answer_match_rate      NUMERIC(5,2),
    score_difference       NUMERIC(10,2),
    risk_level_same        SMALLINT        NOT NULL DEFAULT 0,
    missed_question_count  INTEGER         NOT NULL DEFAULT 0,
    corrected_answer_count INTEGER         NOT NULL DEFAULT 0,
    comparison_summary     TEXT            NOT NULL DEFAULT '',
    creator                VARCHAR(64)     NOT NULL DEFAULT '',
    updator                VARCHAR(64)     NOT NULL DEFAULT '',
    create_time            TIMESTAMP(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time            TIMESTAMP(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted                SMALLINT        NOT NULL DEFAULT 0
);
COMMENT ON TABLE  assessment_comparison IS 'AI 与护士提交的总体对比；是科研分析的核心基础';
COMMENT ON COLUMN assessment_comparison.answer_match_rate IS '答案一致率 0.00-100.00';
CREATE UNIQUE INDEX ux_comparison_instance ON assessment_comparison (assessment_instance_id, ai_submission_id, nurse_submission_id) WHERE deleted = 0;

-- ----------------------------
-- 12. assessment_comparison_item  对比明细
-- ----------------------------
CREATE TABLE assessment_comparison_item (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comparison_id        BIGINT          NOT NULL,
    compare_object_type  VARCHAR(32)     NOT NULL,
    question_id          BIGINT          NOT NULL DEFAULT 0,
    score_code           VARCHAR(64)     NOT NULL DEFAULT '',
    ai_value             TEXT            NOT NULL DEFAULT '',
    nurse_value          TEXT            NOT NULL DEFAULT '',
    same_flag            SMALLINT        NOT NULL DEFAULT 0,
    difference_type      VARCHAR(64)     NOT NULL DEFAULT '',
    difference_reason    VARCHAR(1000)   NOT NULL DEFAULT '',
    creator              VARCHAR(64)     NOT NULL DEFAULT '',
    updator              VARCHAR(64)     NOT NULL DEFAULT '',
    create_time          TIMESTAMP(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time          TIMESTAMP(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted              SMALLINT        NOT NULL DEFAULT 0
);
COMMENT ON TABLE  assessment_comparison_item IS '人机对比明细（按题目或评分项）';
COMMENT ON COLUMN assessment_comparison_item.compare_object_type IS 'question_answer / component_score / total_score / risk_level';
COMMENT ON COLUMN assessment_comparison_item.difference_type     IS 'missed / misjudged / score_error / incomplete_info';
CREATE INDEX ix_comparison_item_cmp ON assessment_comparison_item (comparison_id);
